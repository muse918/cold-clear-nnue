#!/usr/bin/env python3
"""Episode-split, CPU-only architecture experiment; not a trained versus bot.

Train on the explicitly documented hard-drop surrogate teacher generated by
generate.cpp. No hidden bag information is an input. Export the local models
to a dependency-free native evaluator. Raw official tetrio.js is not packaged.
"""
from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import random
import struct
import time

os.environ.setdefault("OMP_NUM_THREADS", "4")
os.environ.setdefault("MKL_NUM_THREADS", "4")
import numpy as np
import torch
from torch import nn
from torch.nn import functional as F


DTYPE = np.dtype([
    ("game", "<u4"), ("parent_id", "<u4"), ("step", "<u2"),
    ("event", "u1"), ("piece", "i1"), ("next", "u1"),
    ("clears", "u1"), ("garbage", "u1"), ("selected", "u1"),
    ("clear_mask", "<u8"), ("reward", "<f4"), ("target", "<f4"),
    ("parent", "<u2", (40,)), ("child", "<u2", (40,)),
    ("row_source", "i1", (40,)), ("placed", "<u2", (4,)),
])
assert DTYPE.itemsize == 240


def boards_and_patches(rows: np.ndarray):
    bits = ((rows[:, :, None] >> np.arange(10)) & 1).astype(np.float32)
    patterns = np.zeros((len(rows), 37, 8), dtype=np.int64)
    for dy in range(4):
        for dx in range(3):
            patterns |= bits[:, dy:dy+37, dx:dx+8].astype(np.int64) << (3*dy+dx)
    return torch.from_numpy(bits), torch.from_numpy(patterns)


def all_patterns():
    return ((torch.arange(4096)[:, None] >> torch.arange(12)) & 1).float()


class LocalModel(nn.Module):
    def __init__(self, kind: str):
        super().__init__()
        self.kind = kind
        self.posdim = 128 if kind == "cell" else 32
        self.position = nn.Linear(400, self.posdim)
        self.register_buffer("pattern_bits", all_patterns(), persistent=False)
        if kind != "cell":
            self.local = nn.Sequential(nn.Linear(12, 16), nn.ReLU(), nn.Linear(16, 16), nn.ReLU())
        if kind == "attention":
            self.logits = nn.Linear(16, 2)
            self.values = nn.Linear(16, 16)
        self.featdim = self.posdim + 7 + (0 if kind == "cell" else 128)
        self.head = nn.Linear(self.featdim, 32)
        self.output = nn.Linear(32, 1)

    def table(self):
        enc = self.local(self.pattern_bits)
        if self.kind == "cnn":
            return enc
        # Each learned logit vector is a fixed query over the local keys.
        # Clamp is part of the trained function and is also compiled into LUT.
        weight = self.logits(enc).clamp(-5.0, 5.0).exp()
        value = self.values(enc).reshape(4096, 2, 8).tanh()
        return torch.cat((weight[:, :, None] * value, weight[:, :, None]), dim=-1).reshape(4096, 18)

    def forward(self, bits, patches, next_piece):
        pos = self.position(bits.flatten(1)).relu()
        if self.kind == "cell":
            features = pos
        else:
            tokens = F.embedding(patches, self.table())
            pooled = tokens.sum(dim=1)
            if self.kind == "cnn":
                spatial = (pooled / 37.0).flatten(1)
            else:
                pooled = pooled.reshape(-1, 8, 2, 9)
                spatial = (pooled[..., :8] / pooled[..., 8:9]).flatten(1)
            features = torch.cat((spatial, pos), dim=1)
        context = F.one_hot(next_piece, 7).float()
        return self.output(self.head(torch.cat((features, context), dim=1)).relu()).squeeze(1)


class DenseCNN(nn.Module):
    """Two spatial layers, effective 5x5 receptive field; reference only."""
    def __init__(self):
        super().__init__()
        self.conv = nn.Sequential(nn.Conv2d(1, 8, 3, padding=1), nn.ReLU(),
                                  nn.Conv2d(8, 16, 3, padding=1), nn.ReLU())
        self.position = nn.Linear(400, 32)
        self.head = nn.Sequential(nn.Linear(160+32+7, 64), nn.ReLU(), nn.Linear(64, 1))

    def forward(self, bits, patches, next_piece):
        spatial = self.conv(bits[:, None]).mean(dim=2).flatten(1)
        pos = self.position(bits.flatten(1)).relu()
        return self.head(torch.cat((spatial, pos, F.one_hot(next_piece, 7).float()), dim=1)).squeeze(1)


class RowTransformer(nn.Module):
    """One content-dependent self-attention block; 40 row tokens, no dropout."""
    def __init__(self):
        super().__init__()
        self.input = nn.Linear(10, 32)
        self.positions = nn.Parameter(torch.randn(1, 40, 32) * .02)
        self.attn = nn.MultiheadAttention(32, 4, dropout=0.0, batch_first=True)
        self.norm1 = nn.LayerNorm(32)
        self.norm2 = nn.LayerNorm(32)
        self.ff = nn.Sequential(nn.Linear(32, 64), nn.ReLU(), nn.Linear(64, 32))
        self.head = nn.Sequential(nn.Linear(32+7, 32), nn.ReLU(), nn.Linear(32, 1))

    def forward(self, bits, patches, next_piece):
        x = self.input(bits) + self.positions
        y = self.norm1(x)
        x = x + self.attn(y, y, y, need_weights=False)[0]
        x = x + self.ff(self.norm2(x))
        return self.head(torch.cat((x.mean(dim=1), F.one_hot(next_piece, 7).float()), dim=1)).squeeze(1)


@torch.no_grad()
def predict(model, bits, patches, next_piece, indices, batch=512):
    model.eval()
    out = []
    for start in range(0, len(indices), batch):
        ids = indices[start:start+batch]
        out.append(model(bits[ids], patches[ids], next_piece[ids]).numpy())
    return np.concatenate(out) if out else np.array([], np.float32)


def ranking_metrics(records, ids, prediction):
    target = records["target"][ids].astype(np.float64)
    qtrue = target + records["reward"][ids]
    qpred = prediction + records["reward"][ids]
    parent = records["parent_id"][ids]
    boundaries = np.r_[0, np.flatnonzero(parent[1:] != parent[:-1])+1, len(ids)]
    regrets, agrees, margins = [], [], []
    for start, end in zip(boundaries[:-1], boundaries[1:]):
        if end-start < 2 or records["event"][ids[start]] != 0:
            continue
        truth, estimate = qtrue[start:end], qpred[start:end]
        best = truth.max()
        regret = best - truth[int(estimate.argmax())]
        regrets.append(float(regret))
        agrees.append(bool(regret <= 1e-4))
        margins.append(float(np.partition(truth, -2)[-1]-np.partition(truth, -2)[-2]))
    error = prediction-target
    return {"samples":len(ids), "groups":len(regrets),
            "rmse":float(np.sqrt(np.mean(error*error))),
            "mae":float(np.mean(np.abs(error))),
            "top_action_agreement":float(np.mean(agrees)),
            "mean_teacher_regret":float(np.mean(regrets)),
            "p95_teacher_regret":float(np.percentile(regrets, 95)),
            "median_teacher_margin":float(np.median(margins))}


def export(model: LocalModel, path: Path, mean: float, std: float):
    """See kernels.cpp for a byte-identical, versioned little-endian reader."""
    def arr(x):
        return x.detach().cpu().numpy().astype("<f4", copy=False).tobytes()
    kind = {"cell":0, "cnn":1, "attention":2}[model.kind]
    dim = {"cell":0, "cnn":16, "attention":18}[model.kind]
    with path.open("wb") as f:
        f.write(b"SPATIALNNUEv1\0\0\0")
        f.write(struct.pack("<5I2f", kind, dim, model.posdim, model.featdim, 32, mean, std))
        if kind:
            f.write(arr(model.table()))
        f.write(arr(model.position.weight.T.contiguous()))
        f.write(arr(model.position.bias))
        f.write(arr(model.head.weight.T.contiguous()))
        f.write(arr(model.head.bias))
        f.write(arr(model.output.weight.flatten()))
        f.write(arr(model.output.bias))
    if kind:
        with path.with_suffix(".encoder.f32").open("wb") as f:
            for layer in (model.local[0], model.local[2]):
                f.write(arr(layer.weight.T.contiguous()))
                f.write(arr(layer.bias))
            if kind == 2:
                for layer in (model.logits, model.values):
                    f.write(arr(layer.weight.T.contiguous()))
                    f.write(arr(layer.bias))
    return path.stat().st_size


@torch.no_grad()
def check_compiled_encoder(model: LocalModel):
    """Independent Conv2d calculation for all 4096 possible local patches."""
    images=model.pattern_bits.reshape(4096,1,4,3)
    conv1=F.conv2d(images,model.local[0].weight.reshape(16,1,4,3),model.local[0].bias).relu()
    conv2=F.conv2d(conv1,model.local[2].weight.reshape(16,16,1,1),model.local[2].bias).relu()
    enc=conv2.flatten(1)
    if model.kind == "cnn":
        expected=enc
    else:
        w=F.linear(enc,model.logits.weight,model.logits.bias).clamp(-5,5).exp()
        v=F.linear(enc,model.values.weight,model.values.bias).reshape(4096,2,8).tanh()
        expected=torch.cat((w[:,:,None]*v,w[:,:,None]),dim=-1).reshape(4096,18)
    actual=model.table()
    assert torch.isfinite(actual).all()
    torch.testing.assert_close(actual,expected,rtol=2e-5,atol=2e-5)
    return {"patterns":4096,"max_abs":float((actual-expected).abs().max()),
            "reference":"Conv2d(4x3), ReLU, Conv2d(1x1), ReLU; optional fixed-query logits/values"}


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--data", type=Path, default=Path(__file__).parent/"data/records.bin")
    p.add_argument("--out", type=Path, default=Path(__file__).parent/"results")
    p.add_argument("--models", default="cell,cnn,attention,dense_cnn,transformer")
    p.add_argument("--epochs", type=int, default=16)
    p.add_argument("--batch", type=int, default=384)
    p.add_argument("--seed", type=int, default=918)
    p.add_argument("--threads", type=int, default=4)
    p.add_argument("--distill", type=Path, help="Optional trained reference checkpoint; target=0.5 teacher+0.5 original")
    args = p.parse_args()
    torch.set_num_threads(args.threads)
    torch.set_num_interop_threads(1)
    torch.use_deterministic_algorithms(True)
    args.out.mkdir(parents=True, exist_ok=True)
    records = np.fromfile(args.data, dtype=DTYPE)
    if not len(records):
        raise ValueError("Empty dataset")
    bits, patches = boards_and_patches(records["child"])
    next_piece = torch.from_numpy(records["next"].astype(np.int64))
    # Group all candidate positions from one game into exactly one split.
    # Adjacent game IDs are clean/garbage pairs. Split pairs, so validation
    # cannot accidentally contain only one condition (e.g. game_id % 10 == 2).
    game_mod = (records["game"] // 2) % 10
    train_ids = np.flatnonzero(game_mod >= 3)
    val_ids = np.flatnonzero(game_mod == 2)
    test_ids = np.flatnonzero(game_mod <= 1)
    mean = float(records["target"][train_ids].mean())
    std = max(1e-6, float(records["target"][train_ids].std()))
    normalized = (records["target"].astype(np.float32)-mean)/std
    factories = {"cell":lambda:LocalModel("cell"), "cnn":lambda:LocalModel("cnn"),
                 "attention":lambda:LocalModel("attention"), "dense_cnn":DenseCNN,
                 "transformer":RowTransformer}
    if args.distill:
        ck = torch.load(args.distill, weights_only=False)
        teacher = factories[ck["model"]]()
        teacher.load_state_dict(ck["state_dict"])
        tp = predict(teacher,bits,patches,next_piece,np.arange(len(records)),args.batch)
        tp = (tp*ck["target_std"]+ck["target_mean"]-mean)/std
        normalized = 0.5*normalized+0.5*tp
        del teacher
    target = torch.from_numpy(normalized.astype(np.float32))
    manifest = {"dataset":str(args.data), "records":len(records), "record_bytes":240,
                "train_games":sorted(map(int,np.unique(records["game"][train_ids]))),
                "validation_games":sorted(map(int,np.unique(records["game"][val_ids]))),
                "test_games":sorted(map(int,np.unique(records["game"][test_ids]))),
                "split_rule":"fold=(game_id//2)%10; train>=3, validation=2, test<=1",
                "target_mean":mean,"target_std":std,"epochs_budget":args.epochs,
                "batch_size":args.batch,"torch":torch.__version__,"threads":args.threads,
                "seed":args.seed, "distillation":str(args.distill) if args.distill else None,
                "scope":"Hard-drop surrogate-teacher imitation; no versus winrate or full TETR.IO simulation claim.",
                "models":{}}
    print(json.dumps({k:v for k,v in manifest.items() if k != "models"}), flush=True)
    for name in args.models.split(","):
        random.seed(args.seed); np.random.seed(args.seed); torch.manual_seed(args.seed)
        model = factories[name]()
        optimizer = torch.optim.AdamW(model.parameters(), lr=.0015, weight_decay=.0001)
        rng = np.random.default_rng(args.seed)
        best_loss, best_state, best_epoch = float("inf"), None, 0
        history=[]
        t0=time.perf_counter()
        for epoch in range(args.epochs):
            model.train()
            order=rng.permutation(train_ids)
            losses=[]
            for start in range(0,len(order),args.batch):
                ix=order[start:start+args.batch]
                optimizer.zero_grad(set_to_none=True)
                pred=model(bits[ix],patches[ix],next_piece[ix])
                loss=F.smooth_l1_loss(pred,target[ix],beta=.3)
                loss.backward()
                nn.utils.clip_grad_norm_(model.parameters(),5.0)
                optimizer.step()
                losses.append(loss.item())
            vp=predict(model,bits,patches,next_piece,val_ids,args.batch)*std+mean
            vm=ranking_metrics(records,val_ids,vp)
            # Select on held-out episode mean squared error; test never selects a checkpoint.
            if vm["rmse"] < best_loss:
                best_loss=vm["rmse"]; best_epoch=epoch+1
                best_state={k:v.detach().clone() for k,v in model.state_dict().items()}
            history.append({"epoch":epoch+1,"train_loss":float(np.mean(losses)),"validation":vm})
            print(json.dumps({"model":name,"epoch":epoch+1,"train_loss":history[-1]["train_loss"],
                              "val_rmse":vm["rmse"],"val_regret":vm["mean_teacher_regret"],
                              "seconds":round(time.perf_counter()-t0,2)}),flush=True)
        model.load_state_dict(best_state)
        model.eval()
        pred=predict(model,bits,patches,next_piece,np.arange(len(records)),args.batch)*std+mean
        pred.astype("<f4").tofile(args.out/f"{name}_predictions.f32")
        torch.save({"model":name,"state_dict":model.state_dict(),"target_mean":mean,
                    "target_std":std,"seed":args.seed,"best_epoch":best_epoch},args.out/f"{name}.pt")
        result={"parameters":sum(p.numel() for p in model.parameters()),"best_epoch":best_epoch,
                "training_seconds":time.perf_counter()-t0,
                "validation":ranking_metrics(records,val_ids,pred[val_ids]),
                "test":ranking_metrics(records,test_ids,pred[test_ids]),"history":history}
        for condition,label in [(0,"clean"),(1,"garbage")]:
            ids=test_ids[(records["game"][test_ids]%2)==condition]
            result[f"test_{label}"]=ranking_metrics(records,ids,pred[ids])
        if isinstance(model,LocalModel):
            result["native_model_bytes"]=export(model,args.out/f"{name}.snn",mean,std)
            if name != "cell":
                result["compiled_encoder_parity"]=check_compiled_encoder(model)
        manifest["models"][name]=result
        (args.out/"training_results.json").write_text(json.dumps(manifest,indent=2))
        print(json.dumps({"done":name,"test":result["test"],"bytes":result.get("native_model_bytes")}),flush=True)
        del model,optimizer


if __name__ == "__main__":
    main()
